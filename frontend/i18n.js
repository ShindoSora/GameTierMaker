  const translations = Object.freeze({
    'zh-CN': zhCN,
    'en-US': enUS,
  });

  let currentLocale = normalizeLocale(
    global.document && global.document.documentElement
      ? global.document.documentElement.lang
      : DEFAULT_LOCALE
  );

  function normalizeLocale(locale) {
    const value = String(locale || '').trim().replace('_', '-').toLowerCase();
    if (value === 'en' || value.startsWith('en-')) return 'en-US';
    if (value === 'zh' || value.startsWith('zh-')) return 'zh-CN';
    return DEFAULT_LOCALE;
  }

  function owns(dictionary, key) {
    return Object.prototype.hasOwnProperty.call(dictionary, key);
  }

  function resolve(key, locale) {
    const normalizedKey = String(key || '');
    const localeDictionary = translations[normalizeLocale(locale)];
    if (owns(localeDictionary, normalizedKey)) return localeDictionary[normalizedKey];
    if (owns(zhCN, normalizedKey)) return zhCN[normalizedKey];
    return normalizedKey;
  }

  function interpolate(message, params) {
    if (!params || typeof params !== 'object') return message;
    return message.replace(/\{([A-Za-z0-9_]+)\}/g, function (match, name) {
      if (!owns(params, name) || params[name] === undefined || params[name] === null) return match;
      return String(params[name]);
    });
  }

  function t(key, params) {
    return interpolate(resolve(key, currentLocale), params);
  }

  function setLocale(locale) {
    currentLocale = normalizeLocale(locale);
    if (global.document) {
      global.document.documentElement.lang = currentLocale;
      global.document.title = resolve('app.title', currentLocale);
    }
    return currentLocale;
  }

  function getLocale() {
    return currentLocale;
  }

  function hasKey(key, locale) {
    const dictionary = translations[normalizeLocale(locale || currentLocale)];
    return owns(dictionary, String(key || '')) || owns(zhCN, String(key || ''));
  }

  function readErrorCode(error) {
    if (!error) return '';
    if (typeof error === 'string') return '';
    const candidates = [
      error.code,
      error.error,
      error.details && error.details.error,
      error.detail && error.detail.error,
      error.data && error.data.error,
      error.response && error.response.data && error.response.data.error,
    ];
    const code = candidates.find(function (candidate) {
      return typeof candidate === 'string' && candidate.trim();
    });
    return code ? code.trim() : '';
  }

  function readErrorMessage(error) {
    if (typeof error === 'string') return error;
    if (!error || typeof error !== 'object') return '';
    const candidates = [
      error.message,
      error.details && error.details.message,
      error.detail && typeof error.detail === 'string' ? error.detail : '',
      error.data && error.data.message,
      error.response && error.response.data && error.response.data.message,
    ];
    const message = candidates.find(function (candidate) {
      return typeof candidate === 'string' && candidate.trim();
    });
    return message ? message.trim() : '';
  }

  function getErrorMessage(error, fallbackKey) {
    const code = readErrorCode(error);
    if (code && code !== 'request_failed') {
      const errorKey = code.startsWith('errors.') ? code : `errors.${code}`;
      if (hasKey(errorKey)) return t(errorKey);
    }
    if (fallbackKey && hasKey(fallbackKey)) return t(fallbackKey);
    if (code) {
      const errorKey = code.startsWith('errors.') ? code : `errors.${code}`;
      if (hasKey(errorKey)) return t(errorKey);
    }
    const message = readErrorMessage(error);
    if (currentLocale === 'zh-CN' && message) return message;
    return t('errors.requestFailed');
  }

  global.GameTierI18n = Object.freeze({
    DEFAULT_LOCALE,
    SUPPORTED_LOCALES,
    translations,
    t,
    setLocale,
    getLocale,
    hasKey,
    getErrorMessage,
  });

  setLocale(currentLocale);
